const DICTS: Record<Lang, Dict> = { en, ru, uz }

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: Dict }>({ lang: 'en', setLang: () => {}, t: en })

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const s = localStorage.getItem('msi-lang') as Lang | null
      if (s && LANGS.includes(s)) return s
    } catch { /* storage unavailable */ }
    return 'en'
  })
  const setLang = (l: Lang) => {
    setLangState(l)
    try { localStorage.setItem('msi-lang', l) } catch { /* ignore */ }
  }
  useEffect(() => { document.documentElement.lang = lang === 'uz' ? 'uz' : lang }, [lang])
  return <Ctx.Provider value={{ lang, setLang, t: DICTS[lang] }}>{children}</Ctx.Provider>
}

export const useLang = () => useContext(Ctx)
